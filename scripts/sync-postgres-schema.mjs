import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
const source = readFileSync("prisma/schema.prisma", "utf8");
const header = "// Generated by scripts/sync-postgres-schema.mjs. Edit prisma/schema.prisma first.\n";
const schema = header + source.replace(/datasource db\s*\{[^}]+\}/, 'datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}').replace(/\r\n/g, "\n");
const target = "prisma/postgresql/schema.prisma";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== schema) throw new Error("PostgreSQL schema is out of date. Run npm run db:postgres:schema and create a matching PostgreSQL migration.");
} else {
  mkdirSync("prisma/postgresql", { recursive: true });
  writeFileSync(target, schema);
}
